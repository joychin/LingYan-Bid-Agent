# ---------------------------------------------------------------- 基础设施

def new_doc() -> Document:
    doc = Document()
    # 中文观感：正文与标题都用中文字体（缺省模板是 Calibri，中文全靠系统回退）
    for style_name in ("Normal", "Title", "Heading 1", "Heading 2", "Heading 3"):
        try:
            style = doc.styles[style_name]
        except KeyError:
            continue
        style.font.name = "等线"
        style.element.rPr.rFonts.set(qn("w:eastAsia"), "等线")
        if style_name.startswith("Heading") or style_name == "Title":
            from docx.shared import RGBColor
            style.font.color.rgb = RGBColor(0, 0, 0)
            style.font.bold = True
    return doc


def center(doc: Document, text: str, size: int = 16, bold: bool = True, space_before: int = 6):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if space_before:
        p.paragraph_format.space_before = None
    run = p.add_run(text)
    run.bold = bold
    run.font.size = None if size == 11 else None
    from docx.shared import Pt
    run.font.size = Pt(size)
    return p


def h(doc: Document, text: str, level: int = 1):
    doc.add_heading(text, level=level)


def p(doc: Document, text: str, bold: bool = False, indent: bool = True):
    para = doc.add_paragraph()
    if indent:
        para.paragraph_format.first_line_indent = None
    run = para.add_run(text)
    run.bold = bold
    return para


def bullets(doc: Document, items: list[str]):
    for it in items:
        doc.add_paragraph(it, style="List Bullet")


def table(doc: Document, headers: list[str], rows: list[list[str]], widths: list[int] | None = None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    for i, head in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = head
        for para in cell.paragraphs:
            for run in para.runs:
                run.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = val
    return t


def save(doc: Document, name: str) -> Path:
    ASSETS.mkdir(parents=True, exist_ok=True)
    path = ASSETS / name
    doc.save(path)
    return path


