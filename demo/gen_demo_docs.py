# ---------------------------------------------------------------- 自检与入口

def self_check(paths: list[Path]) -> list[str]:
    problems: list[str] = []
    for path in paths:
        doc = Document(path)
        texts = [para.text for para in doc.paragraphs]
        for tbl in doc.tables:
            for row in tbl.rows:
                for cell in row.cells:
                    texts.append(cell.text)
        full = "\n".join(texts)
        if not full.strip():
            problems.append(f"{path.name}: 内容为空")
        for marker in ("TODO", "XXX", "×××", "？？？"):
            if marker in full:
                problems.append(f"{path.name}: 含占位残留 {marker!r}")
        if path.name != f"{PROJECT}-招标文件.docx" and COMPANY_SHORT not in full:
            problems.append(f"{path.name}: 缺少公司名")
    return problems


