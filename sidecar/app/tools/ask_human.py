"""向用户提问（HITL：run 暂停等待回答，回答作为工具结果续跑）。

配合 agent.py 的 interrupt_on={"ask_human": {"allowed_decisions": ["respond"]}}：
模型调用本工具时 HumanInTheLoopMiddleware 先 interrupt，用户在前端回答后以
respond 决策 resume，回答文本合成为成功 ToolMessage——工具体正常路径下
不会执行。这里只做防御性兜底（未配置 interrupt 或被 approve 直接放行时），
按「工具失败返回错误字符串、不抛异常」的铁则返回提示。
"""

from langchain_core.tools import tool


@tool
def ask_human(question: str, options: str = "", multiple: bool = False, guide_path: str = "") -> str:
    """当你缺少关键信息、或面临需要用户拍板的取舍时，用本工具向用户提问，不要自行猜测。

    question 两段式写法：第一行是一句完整、具体的问题（中文）；随后换一行，
    用一两句说明为什么问、这个选择影响什么，帮用户判断轻重。两段之间就是
    一个普通的换行符，例如：
    "响应文件怎么拆分？
    拆分方案决定下游目录结构与各册分工，选错会大面积重做。"
    换行必须是真实换行符：不要写字面的反斜杠加 n，也不要写 &#10; 之类的
    HTML 实体——两者都会原样显示给用户，且问题与说明的分段会失效。

    options 可选：候选项用「；」分隔（如「只做技术标；技术标+商务标」），前端
    渲染成可点选选项，用户还可补充文字；有明确倾向时在候选项尾部加「（推荐）」
    标记（如「三册分立（资格/商务/技术）（推荐）；技术商务合并+报价单独」），
    前端显示为推荐角标。multiple 为 true 时允许多选（默认单选）。回答以
    「已选：…」+ 补充文字的形式回传。候选项只写进 options 参数本身——不要在
    question 里写 options=…、guide_path=… 这样的赋值行，那行会原样显示给用户
    且候选项不会变成可点选项。完整调用形态（参数各归各位）：
    ask_human(question="已写好的章节要重写哪些？
    已写内容是有效产出，全量重写会多花时间与成本。",
    options="全部重写；只重写我指定的章节（在补充说明里写明）；只重写自查不通过的节（推荐）")

    guide_path 可选：提问涉及让用户查看/修改某个工作台文件时，传该文件的
    work/ 相对路径（如 body/写作指引.md）——前端会在提问卡上渲染「打开」按钮，
    一键在右侧面板打开该文件；不涉及则不传。路径只写进 guide_path 参数本身。

    提问会暂停任务并展示给用户，等待回答后继续。适用场景：招标文件里互相矛盾
    的条款怎么取舍、缺少必须由用户提供的信息（如资质、报价策略）、目录结构
    调整幅度超出授权等。一次只问一个问题；可以明确推断的小事不要问。
    """
    return "[ask_human 未获得用户回答]（本工具需要用户回答后才会继续；请检查 HITL 配置）"
